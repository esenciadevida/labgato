    public function run(): void
    {
        if (app()->environment('production')) {
            return;
        }

        Calculator::query()->delete();

        foreach ($this->calculators() as $item) {
            $calculator = Calculator::create([
                'name' => $item['name'],
                'slug' => $item['slug'],
                'short_description' => $item['short_description'],
                'formula_display' => $item['formula_display'],
                'engine' => 'php_class',
                'engine_reference' => $item['engine'],
                'input_schema' => $item['input_schema'],
                'output_schema' => $item['output_schema'],
                'interpretation_notes' => $item['interpretation_notes'],
                'references' => json_encode($item['references']),
                'status' => ResourceStatus::PUBLISHED,
                'published_at' => now(),
                'seo_title' => $item['seo_title'],
                'seo_description' => $item['seo_description'],
            ]);

            foreach ($item['categories'] as $categoryName) {
                $category = Category::firstOrCreate(
                    ['slug' => Str::slug($categoryName)],
                    ['name' => $categoryName, 'sort_order' => 0, 'is_active' => true]
                );

                $calculator->categories()->syncWithoutDetaching([$category->id]);
            }

            foreach ($item['tags'] as $tagName) {
                $tag = Tag::firstOrCreate(
                    ['slug' => Str::slug($tagName)],
                    ['name' => $tagName]
                );

                $calculator->tags()->syncWithoutDetaching([$tag->id]);
            }
        }
    }

